import type { SurfaceSnapshot } from '@flui-cloud/semantic-surface';
import {
  expectValidSurface,
  expectDeterministicDigest,
  validateSurfaceSemantics,
} from '../../../testing/surface-test-utils';

import {
  SshKeysSurfaceInput,
  SshKeysSurfaceRevision,
  buildSshKeysSurface,
  presentedContent,
  sshKeyEntityRef,
} from './ssh-keys-surface';
import type { SSHKeyDto } from '../../core/api';

function key(over: Partial<SSHKeyDto> = {}): SSHKeyDto {
  return {
    id: 'key-1',
    name: 'laptop',
    publicKey: 'ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAI... user@laptop',
    fingerprint: 'SHA256:abcdefFingerprint==',
    type: 'ed25519',
    createdAt: '2026-01-01T00:00:00.000Z' as unknown as Date,
    isActive: true,
    autoGenerated: false,
    ...over,
  } as SSHKeyDto;
}

function input(over: Partial<SshKeysSurfaceInput> = {}): SshKeysSurfaceInput {
  return {
    keys: [key()],
    isLoading: false,
    selectedKeyIds: new Set(),
    dateSort: 'desc',
    ...over,
  };
}

function snapshotOf(over: Partial<SshKeysSurfaceInput> = {}): SurfaceSnapshot {
  return buildSshKeysSurface(input(over), { revision: 1, generatedAt: '2026-08-20T09:13:00.000Z' });
}

const listScope = (s: SurfaceSnapshot) => s.scopes.find((x) => x.kind === 'list')!;
const rowScope = (s: SurfaceSnapshot, id: string) => s.scopes.find((x) => x.id === `ssh-keys:keys:${id}`)!;

describe('ssh keys surface producer', () => {
  it('emits a snapshot that validates against the real schema and passes semantic checks', () => {
    expectValidSurface(snapshotOf());
  });

  it('renders a byte-identical digest across two calls with the same input (determinism)', () => {
    expectDeterministicDigest(snapshotOf());
  });

  it('names only the page when nothing is checked — no invented selection', () => {
    const snapshot = snapshotOf();
    expect(snapshot.attention).toEqual([{ scopeId: 'ssh-keys', reason: 'route' }]);
    expect(rowScope(snapshot, 'key-1').entities![0].role).toBe('related');
  });

  it('names every checked key in attention, in list order, reason selection — real multi-select', () => {
    const keys = [key(), key({ id: 'key-2', name: 'server' })];
    const snapshot = snapshotOf({ keys, selectedKeyIds: new Set(['key-1', 'key-2']) });
    expect(snapshot.attention).toEqual([
      { scopeId: 'ssh-keys:keys:key-1', entityRef: sshKeyEntityRef('key-1'), reason: 'selection' },
      { scopeId: 'ssh-keys:keys:key-2', entityRef: sshKeyEntityRef('key-2'), reason: 'selection' },
    ]);
    expect(rowScope(snapshot, 'key-1').entities![0].role).toBe('selected');
    expect(rowScope(snapshot, 'key-2').entities![0].role).toBe('selected');
  });

  it('a partial selection marks only the checked rows selected, the rest stay related', () => {
    const keys = [key(), key({ id: 'key-2', name: 'server' })];
    const snapshot = snapshotOf({ keys, selectedKeyIds: new Set(['key-2']) });
    expect(rowScope(snapshot, 'key-1').entities![0].role).toBe('related');
    expect(rowScope(snapshot, 'key-2').entities![0].role).toBe('selected');
    expect(snapshot.attention).toEqual([
      { scopeId: 'ssh-keys:keys:key-2', entityRef: sshKeyEntityRef('key-2'), reason: 'selection' },
    ]);
  });

  it('presents name (as label), type, fingerprint, auto-generated and active flags', () => {
    const snapshot = snapshotOf({ keys: [key({ autoGenerated: true, isActive: false })] });
    const row = rowScope(snapshot, 'key-1');
    expect(row.entities![0].label).toBe('laptop');
    expect(row.observations!.find((o) => o.key === 'flui.ssh_key.type')?.presentedAs.text).toBe('ed25519');
    expect(row.observations!.find((o) => o.key === 'flui.ssh_key.fingerprint')?.presentedAs.text).toBe('SHA256:abcdefFingerprint==');
    expect(row.observations!.find((o) => o.key === 'flui.ssh_key.auto_generated')?.presentedAs.value).toBe(true);
    expect(row.observations!.find((o) => o.key === 'flui.ssh_key.active')?.presentedAs.value).toBe(false);
  });

  it('redacts: the raw public key material never reaches the snapshot — this page manages metadata only', () => {
    const json = JSON.stringify(snapshotOf());
    expect(json).not.toContain('AAAAC3NzaC1lZDI1NTE5');
    expect(json).not.toContain('publicKey');
  });

  it('marks loading/empty from the real signals, never inventing rows', () => {
    const loading = snapshotOf({ keys: [], isLoading: true });
    expect(listScope(loading).state).toEqual({ loading: true, empty: true });
  });

  it('bumps the revision on real change (a selection), and validateSurfaceSemantics accepts it against the previous snapshot', () => {
    const tracker = new SshKeysSurfaceRevision();
    const first = buildSshKeysSurface(input(), { revision: tracker.next(presentedContent(input())), generatedAt: '2026-08-20T09:13:00.000Z' });
    const selected = input({ selectedKeyIds: new Set(['key-1']) });
    const second = buildSshKeysSurface(selected, { revision: tracker.next(presentedContent(selected)), generatedAt: '2026-08-20T09:14:00.000Z' });
    expect(second.surface.revision).toBe(first.surface.revision + 1);
    expect(validateSurfaceSemantics(second, { previousSnapshot: first })).toEqual([]);
  });

  it('does NOT bump the revision when nothing presented actually changed', () => {
    const tracker = new SshKeysSurfaceRevision();
    const r1 = tracker.next(presentedContent(input()));
    const r2 = tracker.next(presentedContent(input()));
    expect(r2).toBe(r1);
  });

  // The invalid-revision check needs a real failing case exercised, not just trusted.
  it('flags a snapshot whose revision does not advance on the previous one', () => {
    const first = snapshotOf();
    const stale = { ...snapshotOf(), surface: { ...snapshotOf().surface, revision: first.surface.revision } };
    const issues = validateSurfaceSemantics(stale, { previousSnapshot: first });
    expect(issues).toEqual([jasmine.objectContaining({ code: 'invalid-revision', severity: 'error' })]);
  });
});
