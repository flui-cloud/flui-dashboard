import { Component, computed, input, output } from '@angular/core';
import { provideIcons } from '@ng-icons/core';
import { lucideArrowDown, lucideArrowUp } from '@ng-icons/lucide';
import type { SSHKeyDto } from '../../../core/api';
import { FlActionsMenu, MenuAction } from '../../../ui/overlays/actions-menu';
import { FlCopyId } from '../../../ui/patterns/copy-id';
import { FlTable } from '../../../ui/patterns/table';
import { FlIcon } from '../../../ui/primitives/icon';
import { FlStatus } from '../../../ui/primitives/status';
import { FlTag } from '../../../ui/primitives/tag';
import {
  ProviderRef,
  ProviderSyncView,
  formatKeyDate,
  keyRowActions,
  providerSyncOf,
  syncToken,
  syncView,
} from './ssh-keys-rows';

export interface KeyAction {
  readonly key: SSHKeyDto;
  readonly action: string;
}

interface KeyRow {
  readonly key: SSHKeyDto;
  readonly selected: boolean;
  readonly sync: readonly ProviderSyncView[];
  readonly actions: readonly MenuAction[];
}

@Component({
  selector: 'app-ssh-keys-table',
  imports: [FlTable, FlCopyId, FlStatus, FlTag, FlIcon, FlActionsMenu],
  providers: [provideIcons({ lucideArrowDown, lucideArrowUp })],
  host: { class: 'block' },
  template: `
    <div class="fl-table-wrap">
      <table flTable density="dense">
        <thead>
          <tr>
            <th scope="col" class="is-fit">
              <input
                type="checkbox"
                aria-label="Select all keys"
                [checked]="allSelected()"
                [indeterminate]="indeterminate()"
                (change)="toggleAll.emit()"
              />
            </th>
            <th scope="col">Name</th>
            <th scope="col">Fingerprint</th>
            <th scope="col">Type</th>
            <th scope="col">Providers</th>
            <th
              scope="col"
              class="is-num"
              [attr.aria-sort]="dateSort() === 'desc' ? 'descending' : 'ascending'"
            >
              <button
                type="button"
                class="inline-flex items-center gap-1 hover:text-fl-ink"
                (click)="toggleSort.emit()"
              >
                Created
                <fl-icon
                  [name]="dateSort() === 'desc' ? 'lucideArrowDown' : 'lucideArrowUp'"
                  [size]="13"
                />
              </button>
            </th>
            <th scope="col" class="is-fit"><span class="fl-sr">Actions</span></th>
          </tr>
        </thead>
        <tbody>
          @for (row of rows(); track row.key.id) {
            <tr [class.is-selected]="row.selected">
              <td class="is-fit">
                <input
                  type="checkbox"
                  [attr.aria-label]="'Select ' + row.key.name"
                  [checked]="row.selected"
                  (change)="toggleKey.emit(row.key.id)"
                />
              </td>
              <td class="fl-cell-name">
                <span class="fl-row flex-nowrap">
                  <span class="block max-w-60 truncate font-medium" [title]="row.key.name">{{
                    row.key.name
                  }}</span>
                  @if (row.key.autoGenerated) {
                    <fl-tag title="Generated by Flui">auto</fl-tag>
                  }
                </span>
              </td>
              <td>
                <fl-copy-id
                  [value]="row.key.fingerprint"
                  [display]="shortFingerprint(row.key.fingerprint)"
                  label="fingerprint"
                  [attr.title]="row.key.fingerprint"
                />
              </td>
              <td class="fl-mono">{{ row.key.type.toUpperCase() }}</td>
              <td>
                @if (row.sync.length === 0) {
                  <span class="text-fl-ink-muted">No active provider</span>
                } @else {
                  <span class="fl-row flex-nowrap">
                    @for (p of row.sync; track p.id) {
                      <fl-status [tone]="p.tone" [label]="p.label" [title]="p.title" />
                    }
                  </span>
                }
              </td>
              <td class="is-num">{{ date(row.key.createdAt) }}</td>
              <td class="is-fit">
                <fl-actions-menu
                  [label]="'Actions for ' + row.key.name"
                  [compact]="true"
                  [items]="row.actions"
                  (action)="action.emit({ key: row.key, action: $event })"
                />
              </td>
            </tr>
          }
        </tbody>
      </table>
    </div>
  `,
})
export class SshKeysTable {
  readonly keys = input.required<readonly SSHKeyDto[]>();
  readonly providers = input.required<readonly ProviderRef[]>();
  readonly selected = input.required<ReadonlySet<string>>();
  readonly syncing = input.required<ReadonlySet<string>>();
  readonly unsyncing = input.required<ReadonlySet<string>>();
  readonly dateSort = input.required<'asc' | 'desc'>();

  readonly toggleKey = output<string>();
  readonly toggleAll = output<void>();
  readonly toggleSort = output<void>();
  readonly action = output<KeyAction>();

  protected readonly date = formatKeyDate;

  protected readonly allSelected = computed(
    () => this.keys().length > 0 && this.keys().every((k) => this.selected().has(k.id)),
  );
  protected readonly indeterminate = computed(
    () => this.selected().size > 0 && !this.allSelected(),
  );

  protected readonly rows = computed<KeyRow[]>(() => {
    const selected = this.selected();
    const syncing = this.syncing();
    const unsyncing = this.unsyncing();
    const providers = this.providers();
    return this.keys().map((key) => {
      const sync = providerSyncOf(key, providers);
      const busy = (id: string) => {
        const token = syncToken(key.id, id);
        return syncing.has(token) || unsyncing.has(token);
      };
      return {
        key,
        selected: selected.has(key.id),
        sync: sync.map((p) =>
          syncView(p, syncing.has(syncToken(key.id, p.id)), unsyncing.has(syncToken(key.id, p.id))),
        ),
        actions: keyRowActions(sync, busy),
      };
    });
  });

  protected shortFingerprint(value: string): string {
    return value.length > 28 ? `${value.slice(0, 26)}…` : value;
  }
}
