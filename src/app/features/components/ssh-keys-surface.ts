import type {
  AttentionTarget,
  Observation,
  SemanticScopeSnapshot,
  SurfaceSnapshot,
} from '@flui-cloud/semantic-surface';

import {
  boolObservation,
  buildSurfaceList,
  entityRef,
  SURFACE_APP_ID,
  SurfaceListRow,
  textObservation,
} from '../../shared/utils/surface-kit';
import type { SSHKeyDto } from '../../core/api';

const PAGE_ID = 'ssh-keys';
const LIST_ID = `${PAGE_ID}:keys`;

export function sshKeyEntityRef(id: string): string {
  return entityRef('ssh-key', id);
}

export interface SshKeysSurfaceInput {
  keys: SSHKeyDto[];
  isLoading: boolean;
  /** Real, per-instance bulk-selection state — the checkboxes in ssh-keys.component.ts,
   * never invented for this producer (playbook §4, §11: the multi-select case). */
  selectedKeyIds: ReadonlySet<string>;
  dateSort: 'asc' | 'desc';
}

export interface SshKeysSurfaceContext {
  revision: number;
  generatedAt: string;
  appVersion?: string;
}

/** `createdAt` is typed `Date` on the DTO but travels as an ISO string over the wire. */
function isoOf(value: unknown): string | undefined {
  if (!value) return undefined;
  return value instanceof Date ? value.toISOString() : String(value);
}

function rowOf(key: SSHKeyDto, selected: boolean): SurfaceListRow {
  return {
    id: `${LIST_ID}:${key.id}`,
    ref: sshKeyEntityRef(key.id),
    label: key.name,
    role: selected ? 'selected' : 'related',
    // Never `publicKey`: the page manages key METADATA, not key material — the playbook
    // calls this out by name. `fingerprint` is a hash-derived identifier the row already
    // renders in the clear (ssh-keys.component.ts's Fingerprint column, and again in the
    // delete-confirmation dialog), not the key itself, so it stays.
    observations: [
      textObservation('flui.ssh_key.type', key.type, 'api'),
      textObservation('flui.ssh_key.fingerprint', key.fingerprint, 'api'),
      boolObservation('flui.ssh_key.auto_generated', !!key.autoGenerated, 'api'),
      boolObservation('flui.ssh_key.active', key.isActive, 'api'),
      textObservation('flui.ssh_key.created_at', isoOf(key.createdAt), 'api'),
    ].filter((o): o is Observation => o !== null),
  };
}

export interface PresentedContent {
  scopes: SemanticScopeSnapshot[];
  attention: AttentionTarget[];
}

/**
 * Everything the SSH Keys page would present, without the revision/timestamp envelope.
 * This page has REAL multi-selection (checkboxes, "N selected", bulk delete) — the case
 * the playbook names as the highest-value still-unbuilt pattern (§11): every selected key
 * is named in `attention`, in list order, `reason: 'selection'`, pointing at that key's
 * own row scope; nothing is selected when nothing is checked.
 */
export function presentedContent(input: SshKeysSurfaceInput): PresentedContent {
  const pageScope: SemanticScopeSnapshot = {
    id: PAGE_ID,
    kind: 'page',
    label: 'SSH Keys',
  };

  const rows = input.keys.map((key) => ({ key, row: rowOf(key, input.selectedKeyIds.has(key.id)) }));

  const { scopes: listScopes } = buildSurfaceList({
    listId: LIST_ID,
    parentId: PAGE_ID,
    label: 'Keys',
    totalCount: input.keys.length,
    rows: rows.map((r) => r.row),
    listObservations: [
      textObservation('flui.ssh_keys.sort_order', input.dateSort, 'ui'),
    ],
  });
  listScopes[0] = {
    ...listScopes[0],
    state: { loading: input.isLoading, empty: input.keys.length === 0 },
  };

  const selected = rows.filter((r) => input.selectedKeyIds.has(r.key.id));
  const attention: AttentionTarget[] =
    selected.length > 0
      ? selected.map((r) => ({ scopeId: r.row.id, entityRef: r.row.ref, reason: 'selection' }))
      : [{ scopeId: PAGE_ID, reason: 'route' }];

  return { scopes: [pageScope, ...listScopes], attention };
}

export function buildSshKeysSurface(
  input: SshKeysSurfaceInput,
  context: SshKeysSurfaceContext,
): SurfaceSnapshot {
  const content = presentedContent(input);
  return {
    schemaVersion: '0.2',
    app: { id: SURFACE_APP_ID, ...(context.appVersion ? { version: context.appVersion } : {}) },
    surface: {
      id: PAGE_ID,
      route: 'infrastructure/keys',
      revision: context.revision,
      generatedAt: context.generatedAt,
    },
    attention: content.attention,
    scopes: content.scopes,
  };
}

export class SshKeysSurfaceRevision {
  private counter = 0;
  private lastHash = '';

  next(presented: PresentedContent): number {
    const hash = JSON.stringify(presented);
    if (hash !== this.lastHash) {
      this.lastHash = hash;
      this.counter += 1;
    }
    return this.counter;
  }
}
